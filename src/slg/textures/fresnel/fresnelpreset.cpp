FresnelTextureUPtr slg::AllocFresnelPresetTex(const Properties &props, const string &propName) {
	const string presetName = props.Get(Property(propName + ".preset")(
			props.Get(Property(propName + ".name")("aluminium")).Get<string>())).Get<string>();

	vector<float> wl;
	vector<float> n;
	vector<float> k;

	if (presetName == "amorphous carbon") {
		wl.assign(AmorphousCarbonWavelengths,
				AmorphousCarbonWavelengths + AmorphousCarbonSamples);
		n.assign(AmorphousCarbonN,
				AmorphousCarbonN + AmorphousCarbonSamples);
		k.assign(AmorphousCarbonK,
				AmorphousCarbonK + AmorphousCarbonSamples);
	} else if (presetName == "silver") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(SilverN, SilverN + SopraSamples);
		k.assign(SilverK, SilverK + SopraSamples);
	} else if (presetName == "gold") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(GoldN, GoldN + SopraSamples);
		k.assign(GoldK, GoldK + SopraSamples);
	} else if (presetName == "copper") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(CopperN, CopperN + SopraSamples);
		k.assign(CopperK, CopperK + SopraSamples);
	} else if (presetName == "aluminium") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(AluminiumN, AluminiumN + SopraSamples);
		k.assign(AluminiumK, AluminiumK + SopraSamples);
	} else if (presetName == "chromium") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(ChromiumN, ChromiumN + SopraSamples);
		k.assign(ChromiumK, ChromiumK + SopraSamples);
	} else if (presetName == "titanium") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(TitaniumN, TitaniumN + SopraSamples);
		k.assign(TitaniumK, TitaniumK + SopraSamples);
	} else if (presetName == "nickel") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(NickelN, NickelN + SopraSamples);
		k.assign(NickelK, NickelK + SopraSamples);
	} else if (presetName == "iron") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(IronN, IronN + SopraSamples);
		k.assign(IronK, IronK + SopraSamples);
	} else if (presetName == "cobalt") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(CobaltN, CobaltN + SopraSamples);
		k.assign(CobaltK, CobaltK + SopraSamples);
	} else if (presetName == "palladium") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(PalladiumN, PalladiumN + SopraSamples);
		k.assign(PalladiumK, PalladiumK + SopraSamples);
	} else if (presetName == "vanadium") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(VanadiumN, VanadiumN + SopraSamples);
		k.assign(VanadiumK, VanadiumK + SopraSamples);
	} else if (presetName == "platinum") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(PlatinumN, PlatinumN + SopraSamples);
		k.assign(PlatinumK, PlatinumK + SopraSamples);
	} else if (presetName == "tungsten") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(TungstenN, TungstenN + SopraSamples);
		k.assign(TungstenK, TungstenK + SopraSamples);
	} else if (presetName == "zinc") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(ZincN, ZincN + SopraSamples);
		k.assign(ZincK, ZincK + SopraSamples);
	} else if (presetName == "molybdenum") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(MolybdenumN, MolybdenumN + SopraSamples);
		k.assign(MolybdenumK, MolybdenumK + SopraSamples);
	} else if (presetName == "tantalum") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(TantalumN, TantalumN + SopraSamples);
		k.assign(TantalumK, TantalumK + SopraSamples);
	} else if (presetName == "lead") {
		wl.assign(SopraWavelengths, SopraWavelengths + SopraSamples);
		n.assign(LeadN, LeadN + SopraSamples);
		k.assign(LeadK, LeadK + SopraSamples);
	} else
		throw runtime_error("Unknown Fresnel preset name: " + presetName);

	IrregularSPD N(&wl[0], &n[0], wl.size());
	IrregularSPD K(&wl[0], &k[0], wl.size());

	ColorSystem colorSpace(.63f, .34f, .31f, .595f, .155f, .07f,
		1.f / 3.f, 1.f / 3.f, 1.f);
	const RGBColor Nrgb = colorSpace.ToRGBConstrained(N.ToNormalizedXYZ());
	const RGBColor Krgb = colorSpace.ToRGBConstrained(K.ToNormalizedXYZ());

	return std::make_unique<FresnelConstTexture>(Nrgb, Krgb);
}
